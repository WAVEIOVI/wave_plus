<?php

declare(strict_types=1);

namespace App\Modules\Catalog\Services;

use App\Modules\Catalog\Models\CatalogItem;
use App\Modules\Catalog\Models\CatalogVariant;

class CatalogLineSnapshotService
{
    /**
     * Frozen catalog facts for transactional document lines.
     * Live catalog edits must not rewrite these values.
     *
     * @param  array<string, mixed>  $line
     * @return array<string, mixed>
     */
    public function forLine(array $line): array
    {
        $itemId = $line['catalog_item_id'] ?? null;
        $variantId = $line['variant_id'] ?? null;

        if (! $itemId) {
            return [
                'description_snapshot' => $line['description_snapshot']
                    ?? $line['description_override']
                    ?? $line['ad_hoc_name']
                    ?? null,
                'sku_snapshot' => $line['sku_snapshot'] ?? $line['ad_hoc_sku'] ?? null,
                'uom_code_snapshot' => $line['uom_code_snapshot'] ?? null,
            ];
        }

        $item = CatalogItem::query()->with(['uom'])->find($itemId);
        $variant = $variantId
            ? CatalogVariant::query()->find($variantId)
            : $item?->variants()->where('is_default', true)->first();

        $name = $item?->getTranslation('name', 'en')
            ?: (is_array($item?->name) ? (string) reset($item->name) : (string) $item?->name);

        return [
            'description_snapshot' => $line['description_snapshot']
                ?? $line['description_override']
                ?? ($name !== '' ? $name : null),
            'sku_snapshot' => $line['sku_snapshot'] ?? $variant?->sku ?? $item?->code,
            'uom_code_snapshot' => $line['uom_code_snapshot'] ?? $item?->uom?->code,
        ];
    }

    /**
     * Snapshot for a Blueprint-generated line.
     *
     * The description_snapshot identifies both:
     *   1. The Catalog Item / Service name
     *   2. The configured Blueprint equipment identity (equipment name with selected options)
     *
     * Example output:
     *   "Refill Powder — Fire Extinguisher POWDER 09kg / Permanent Pressure"
     *
     * This snapshot is historical and must not change when the Blueprint is later modified.
     *
     * @param  array<string, mixed>  $line
     * @param  string  $equipmentName  Generated by BlueprintCalculationService::generateEquipmentName()
     * @return array<string, mixed>
     */
    public function forBlueprintLine(array $line, string $equipmentName): array
    {
        $base = $this->forLine($line);

        // If a description_snapshot was already explicitly provided, keep it.
        if (! empty($line['description_snapshot'])) {
            return $base;
        }

        // Build "ItemName — EquipmentName" snapshot
        $itemName = $base['description_snapshot'] ?? null;

        if ($itemName && $equipmentName) {
            $base['description_snapshot'] = "{$itemName} — {$equipmentName}";
        } elseif ($equipmentName) {
            $base['description_snapshot'] = $equipmentName;
        }

        return $base;
    }
}
