                    color="primary"
                    variant="tonal"
                    class="font-mono font-weight-bold"
                  >
                    {{ formData.silhouette }}
                  </VChip>
                </div>

                <div class="garment-drawing-viewport d-flex justify-center align-center bg-surface">
                  <WorkwearGarmentIllustration
                    v-model:active-view="previewView"
                    :silhouette="formData.silhouette"
                    :colors="formData.colors"
                    readonly
                    compact
                    :show-callouts="false"
                  />
                </div>

                <div class="pa-3 border-t bg-var-theme-background text-center">
                  <div class="text-caption font-weight-bold text-high-emphasis text-truncate">
                    {{ silhouetteSummary.itemTitle }}
                  </div>
                  <div class="text-caption text-medium-emphasis text-truncate mt-0.5">
                    {{ silhouetteSummary.categoryTitle }} › {{ silhouetteSummary.subcategoryTitle }}
                  </div>

                  <div class="d-flex align-center justify-center gap-2 mt-2">
                    <div class="d-flex align-center gap-1">
                      <span
                        class="d-inline-block rounded-circle border elevation-1"
                        :style="{ width: '12px', height: '12px', backgroundColor: resolveColorHex(formData.colors[0], '#1e293b') }"
                      />
                      <span class="text-caption text-capitalize font-weight-medium">
                        {{ resolveColorName(formData.colors[0]) }}
                      </span>
