<script setup>
/* eslint-disable camelcase */
import WpWizardDialog from '@/components/shared/wizard/WpWizardDialog.vue'
import {
  extractCatalogColorsAndSizes,
  resolveColorHex,
  resolveSilhouetteDisplay,
  useWorkwearStudioConstants,
} from '@/composables/client-assets/workwear/useWorkwearStudioConstants'
import { localizedValue } from '@/composables/useLocaleField'
import { useClientAssetStore } from '@/stores/useClientAssetStore'
import { useSnackbarStore } from '@/stores/useSnackbarStore'
import CatalogZoomDialog from '@/views/catalog/shared/CatalogZoomDialog.vue'
import WorkwearGarmentIllustration from '@/views/client-assets/workwear/models/components/WorkwearGarmentIllustration.vue'
import WorkwearWizardCatalogStep from '@/views/client-assets/workwear/models/list/components/WorkwearWizardCatalogStep.vue'
import WorkwearWizardClientStep from '@/views/client-assets/workwear/models/list/components/WorkwearWizardClientStep.vue'
import WorkwearWizardSilhouetteStep from '@/views/client-assets/workwear/models/list/components/WorkwearWizardSilhouetteStep.vue'
import { computed, ref, watch } from 'vue'
import { useI18n } from 'vue-i18n'
import { useRouter } from 'vue-router'

const props = defineProps({
  isDialogVisible: { type: Boolean, required: true },
})

const emit = defineEmits(['update:isDialogVisible', 'modelCreated', 'addModel'])

const { t, locale } = useI18n()
const router = useRouter()
const store = useClientAssetStore()
const snackbarStore = useSnackbarStore()
const { resolveColorName } = useWorkwearStudioConstants()

const isSubmitting = ref(false)
const isVariantsZoomOpen = ref(false)
const previewView = ref('front')

const selectedClient = ref(null)
const selectedCatalogItem = ref(null)

const formData = ref(getInitialForm())

function getInitialForm() {
  return {
    client_id: null,
    catalog_item_id: null,
    supplier_id: null,
    silhouette_category: 'clothing',
    silhouette_subcategory: 'one_piece',
    silhouette_item: 'single_zip_coverall',
    silhouette: 'coverall',
    fabric_id: null,
    fabric: '',
    colors: ['navy', 'hi-vis-yellow'],
    size_range: ['S', 'M', 'L', 'XL', '2XL'],
    standards: [],
    certifications: [],
  }
}

const selectedFabricObj = computed(() =>
  (store.workwearFabrics || []).find(f => f.id === formData.value.fabric_id) || null,
)

const silhouetteSummary = computed(() =>
  resolveSilhouetteDisplay(formData.value, { locale: locale.value, t }),
)

// Auto-generated Workwear Model Name (Read-only, editable in edit page after save)
const autoGeneratedModelName = computed(() => {
  const clientObj = selectedClient.value
  const clientIdentifier = clientObj?.client_id || clientObj?.code || localizedValue(clientObj?.legal_name) || (formData.value.client_id ? `#${String(formData.value.client_id).slice(-6)}` : '')

  const catalogName = selectedCatalogItem.value
    ? (localizedValue(selectedCatalogItem.value.name, locale.value) || selectedCatalogItem.value.code)
    : silhouetteSummary.value.itemTitle

  if (catalogName && clientIdentifier) {
    return `${catalogName} — ${clientIdentifier}`
  }
  if (catalogName) {
    return catalogName
  }

  return t('Workwear Model')
})

// Wizard Steps Definition
const wizardSteps = computed(() => [
  {
    id: 'client',
    key: 'client',
    title: t('Client Selection'),
    subtitle: t('Assign owning client company'),
    icon: 'tabler-building-store',
    valid: Boolean(formData.value.client_id),
    validate: () => {
      if (!formData.value.client_id) {
        return t('Please select a client company.')
      }

      return true
    },
  },
  {
    id: 'catalog',
    key: 'catalog',
    title: t('Catalog Product'),
    subtitle: t('Physical product & options'),
    icon: 'tabler-package',
    valid: true,
    validate: () => true,
  },
  {
    id: 'silhouette_fabric',
    key: 'silhouette_fabric',
    title: t('Silhouette & Textile'),
    subtitle: t('Garment cards, fabric, colors & sizes'),
    icon: 'tabler-shirt',
    valid: Boolean(formData.value.silhouette),
    validate: () => {
      if (!formData.value.silhouette) {
        return t('Please choose a garment silhouette.')
      }

      return true
    },
  },
])

async function fetchLookupData() {
  try {
    await store.fetchWorkwearFabrics({ per_page: 100, 'filter[is_active]': 1, seed_if_empty: 1 })
    if (!formData.value.fabric_id && store.workwearFabrics?.length) {
      const firstFabric = store.workwearFabrics[0]

      formData.value.fabric_id = firstFabric.id
      formData.value.fabric = firstFabric.name
    }
  } catch (err) {
    console.error('Failed to load workwear fabrics:', err)
  }
}

watch(() => props.isDialogVisible, val => {
  if (val) {
    fetchLookupData()
  }
}, { immediate: true })

function handleClientSelect(client) {
  selectedClient.value = client
  formData.value.client_id = client?.id || null
}

async function handleCatalogItemSelect(catalogItem) {
  if (!catalogItem) {
    formData.value.catalog_item_id = null
    formData.value.supplier_id = null
    selectedCatalogItem.value = null

    return
  }

  const itemId = catalogItem.id

  formData.value.catalog_item_id = itemId

  let fullItem = catalogItem
  try {
    const fetched = await store.fetchCatalogItemDetails(itemId)
    if (fetched) fullItem = fetched
  } catch {
    // Fallback to list item
  }

  selectedCatalogItem.value = fullItem

  // Auto-populate preferred supplier from catalog item
  const prefSupplierId = fullItem.preferred_supplier_id
    || fullItem.preferred_supplier?.id
    || fullItem.suppliers?.[0]?.id
    || null

  formData.value.supplier_id = prefSupplierId

  // Automatically import BOTH colors and sizes from catalog item options
  const extracted = extractCatalogColorsAndSizes(fullItem, locale.value)
  if (extracted.colors.length) {
    formData.value.colors = extracted.colors.slice(0, 2)
  }
  if (extracted.sizes.length) {
    formData.value.size_range = [...extracted.sizes]
  }

  // Import certifications from catalog item if present
  if (Array.isArray(fullItem.certifications) && fullItem.certifications.length) {
    formData.value.certifications = [...fullItem.certifications]
  }
}

function resetForm() {
  formData.value = getInitialForm()
  selectedClient.value = null
  selectedCatalogItem.value = null
}

function closeDialog() {
  emit('update:isDialogVisible', false)
  resetForm()
}

async function onSubmit() {
  if (!formData.value.client_id) {
    throw new Error(t('Please select a client company.'))
  }

  const finalName = autoGeneratedModelName.value || t('Workwear Model')

  isSubmitting.value = true
  try {
    const res = await store.createWorkwearModel({
      client_id: formData.value.client_id,
      catalog_item_id: formData.value.catalog_item_id || null,
      supplier_id: formData.value.supplier_id || null,
      name: finalName.trim(),
      status: 'draft',
      silhouette_category: formData.value.silhouette_category || null,
      silhouette_subcategory: formData.value.silhouette_subcategory || null,
      silhouette_item: formData.value.silhouette_item || null,
      silhouette: formData.value.silhouette || 'coverall',
      fabric_id: formData.value.fabric_id || null,
      fabric: formData.value.fabric || selectedFabricObj.value?.name || null,
      colors: formData.value.colors,
      size_range: formData.value.size_range,
      certifications: formData.value.certifications,
      standards: formData.value.standards,
      notes: null,
    })

    const createdModel = res?.data

    snackbarStore.showMessage(t('Workwear model created successfully'), 'success')
    emit('modelCreated', createdModel)
    emit('addModel', createdModel)
    emit('update:isDialogVisible', false)

    resetForm()

    if (createdModel?.id) {
      router.push({
        name: 'client-assets-workwear-edit-id',
        params: { id: createdModel.id },
        query: { type: 'model' },
      })
    }

    return createdModel
  } catch (err) {
    const msg = err?.data?.message || err?.message || t('Failed to create model')

    snackbarStore.showMessage(msg, 'error')
    throw err
  } finally {
    isSubmitting.value = false
  }
}
</script>

<template>
  <WpWizardDialog
    :model-value="props.isDialogVisible"
    :title="$t('New Workwear & PPE Model')"
    :description="$t('Configure client ownership, physical catalog product, silhouette taxonomy & technical textile')"
    icon="tabler-shirt"
    variant="standard"
    :max-width="1040"
    :steps="wizardSteps"
    review
    :submit="onSubmit"
    :submit-label="$t('Create Workwear Model')"
    :confirm-discard="false"
    @update:model-value="val => { if (!val) closeDialog() }"
    @cancel="closeDialog"
  >
    <!-- ━━━ STEP 1: CLIENT SELECTION ━━━ -->
    <template #step-client>
      <WorkwearWizardClientStep
        :client="selectedClient"
        @update:client="handleClientSelect"
      />
    </template>

    <!-- ━━━ STEP 2: PHYSICAL CATALOG PRODUCT ━━━ -->
    <template #step-catalog>
      <WorkwearWizardCatalogStep
        :catalog-item="selectedCatalogItem"
        @update:catalog-item="handleCatalogItemSelect"
        @view-variants="isVariantsZoomOpen = true"
      />
    </template>

    <!-- ━━━ STEP 3: SILHOUETTE CLASSIFICATION CARDS, FABRIC, COLORS & SIZES ━━━ -->
    <template #step-silhouette_fabric>
      <WorkwearWizardSilhouetteStep
        v-model:category="formData.silhouette_category"
        v-model:subcategory="formData.silhouette_subcategory"
        v-model:silhouette-item="formData.silhouette_item"
        v-model:silhouette="formData.silhouette"
        v-model:fabric-id="formData.fabric_id"
        v-model:fabric="formData.fabric"
        v-model:colors="formData.colors"
        v-model:size-range="formData.size_range"
        :catalog-item="selectedCatalogItem"
        :fabrics="store.workwearFabrics || []"
      />
    </template>

    <!-- ━━━ STEP 4: READ-ONLY REVIEW ━━━ -->
    <template #review>
      <div class="d-flex flex-column gap-4">
        <VRow>
          <!-- Left Column: Read-Only Specifications Summary -->
          <VCol
            cols="12"
            md="7"
          >
            <div class="d-flex flex-column gap-4">
              <!-- Specifications Review List -->
              <VCard variant="outlined">
                <VList density="comfortable">
                  <!-- 0. Name that will be created -->
                  <VListItem>
                    <template #prepend>
                      <VIcon
                        icon="tabler-tag"
                        color="primary"
                      />
                    </template>
                    <VListItemTitle class="text-caption text-medium-emphasis">
                      {{ $t('Model Name') }}
                    </VListItemTitle>
                    <VListItemSubtitle class="text-body-1 font-weight-bold text-high-emphasis text-wrap">
                      {{ autoGeneratedModelName }}
                    </VListItemSubtitle>
                    <VListItemSubtitle class="text-caption text-wrap mt-1">
                      {{ $t('You can rename it after creating the model.') }}
                    </VListItemSubtitle>
                  </VListItem>

                  <VDivider />

                  <!-- 1. Client Item -->
                  <VListItem>
                    <template #prepend>
                      <VIcon
                        icon="tabler-building-store"
                        color="primary"
                      />
                    </template>
                    <VListItemTitle class="text-caption text-medium-emphasis">
                      {{ $t('Owning Client') }}
                    </VListItemTitle>
                    <VListItemSubtitle class="text-body-1 font-weight-bold text-high-emphasis">
                      {{ localizedValue(selectedClient?.legal_name) || selectedClient?.legal_name || selectedClient?.name || '—' }}
                      <span
                        v-if="selectedClient?.client_id || selectedClient?.code"
                        class="text-caption font-mono text-medium-emphasis ms-1"
                      >
                        ({{ selectedClient.client_id || selectedClient.code }})
                      </span>
                    </VListItemSubtitle>
                  </VListItem>

                  <VDivider />

                  <!-- 2. Catalog Product & Preferred Supplier -->
                  <VListItem>
                    <template #prepend>
                      <VIcon
                        icon="tabler-package"
                        color="info"
                      />
                    </template>
                    <VListItemTitle class="text-caption text-medium-emphasis">
                      {{ $t('Linked Catalog Product & Preferred Supplier') }}
                    </VListItemTitle>
                    <VListItemSubtitle class="text-body-2 font-weight-medium text-high-emphasis">
                      <template v-if="selectedCatalogItem">
                        <span class="font-mono font-weight-bold text-primary me-1">{{ selectedCatalogItem.code }}</span>
                        — {{ localizedValue(selectedCatalogItem.name, locale) }}
                        <div
                          v-if="selectedCatalogItem.preferred_supplier?.legal_name"
                          class="text-success text-caption font-weight-semibold mt-1"
                        >
                          <VIcon
                            icon="tabler-truck-delivery"
                            size="14"
                            class="me-1"
                          />
                          {{ $t('Preferred Supplier:') }} {{ selectedCatalogItem.preferred_supplier.legal_name }}
                        </div>
                      </template>
                      <template v-else>
                        <span class="text-medium-emphasis font-italic">{{ $t('No physical catalog product linked (Custom Model)') }}</span>
                      </template>
                    </VListItemSubtitle>
                  </VListItem>

                  <VDivider />

                  <!-- 3. Silhouette Taxonomy -->
                  <VListItem>
                    <template #prepend>
                      <VIcon
                        icon="tabler-hierarchy-2"
                        color="success"
                      />
                    </template>
                    <VListItemTitle class="text-caption text-medium-emphasis">
                      {{ $t('Silhouette Classification') }}
                    </VListItemTitle>
                    <VListItemSubtitle class="text-body-2 font-weight-medium text-high-emphasis">
                      {{ silhouetteSummary.categoryTitle }} › {{ silhouetteSummary.subcategoryTitle }} › <strong>{{ silhouetteSummary.itemTitle }}</strong>
                    </VListItemSubtitle>
                  </VListItem>

                  <VDivider />

                  <!-- 4. Technical Fabric, Color Scheme & Sizes -->
                  <VListItem>
                    <template #prepend>
                      <VIcon
                        icon="tabler-layers-intersect"
                        color="warning"
                      />
                    </template>
                    <VListItemTitle class="text-caption text-medium-emphasis">
                      {{ $t('Technical Fabric, Colors & Sizes') }}
                    </VListItemTitle>
                    <VListItemSubtitle class="d-flex flex-column gap-2 mt-1">
                      <div class="d-flex flex-wrap align-center justify-space-between gap-3">
                        <span class="font-weight-medium text-high-emphasis">
                          {{ selectedFabricObj?.name || formData.fabric || '—' }}
                          <span
                            v-if="selectedFabricObj?.weight_gsm"
                            class="text-caption font-mono ms-1"
                          >
                            ({{ selectedFabricObj.weight_gsm }} g/m²)
                          </span>
                        </span>

                        <div class="d-flex align-center gap-2">
                          <div class="d-flex align-center gap-1">
                            <span
                              class="d-inline-block rounded-circle border"
                              :style="{ width: '14px', height: '14px', backgroundColor: resolveColorHex(formData.colors[0], '#1e293b') }"
                            />
                            <span class="text-caption font-mono">{{ formData.colors[0] }}</span>
                          </div>
                          <template v-if="formData.colors[1]">
                            <span>+</span>
                            <div class="d-flex align-center gap-1">
                              <span
                                class="d-inline-block rounded-circle border"
                                :style="{ width: '14px', height: '14px', backgroundColor: resolveColorHex(formData.colors[1], '#eab308') }"
                              />
                              <span class="text-caption font-mono">{{ formData.colors[1] }}</span>
                            </div>
                          </template>
                        </div>
                      </div>

                      <div
                        v-if="formData.size_range?.length"
                        class="d-flex flex-wrap gap-1"
                      >
                        <VChip
                          v-for="sz in formData.size_range"
                          :key="sz"
                          size="x-small"
                          color="primary"
                          variant="tonal"
                          class="font-mono"
                        >
                          {{ sz }}
                        </VChip>
                      </div>
                    </VListItemSubtitle>
                  </VListItem>
                </VList>
              </VCard>
            </div>
          </VCol>

          <!-- Right Column: Live 2D CAD Garment Preview -->
          <VCol
            cols="12"
            md="5"
            class="order-first order-md-last"
          >
            <div class="sticky-preview">
              <VCard
                variant="outlined"
                class="garment-preview-card overflow-hidden"
              >
                <div class="pa-3 border-b bg-var-theme-background d-flex align-center justify-space-between">
                  <div class="d-flex align-center gap-2">
                    <VIcon
