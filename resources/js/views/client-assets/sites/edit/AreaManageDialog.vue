<script setup>
/* eslint-disable camelcase */
import { WpFormDialog } from '@/components/shared'
import { buildAreaBreadcrumb, generateShortAreaCode, hasCircularDependency } from '@/composables/client-assets/sites/areaHierarchyHelper'
import { resolveAreaTypeIcon } from '@/composables/client-assets/sites/useSiteConstants'
import { resolveAreaName } from '@/composables/client-assets/sites/useSiteAreaTree'
import { localizedValue } from '@/composables/useLocaleField'
import { useClientAssetStore } from '@/stores/useClientAssetStore'
import { useSnackbarStore } from '@/stores/useSnackbarStore'
import { computed, nextTick, ref, watch } from 'vue'
import { useI18n } from 'vue-i18n'
import { useDisplay } from 'vuetify'
import SiteAreaSearchDialog from './SiteAreaSearchDialog.vue'

const props = defineProps({
  modelValue: { type: Boolean, default: undefined },
  isDialogVisible: { type: Boolean, default: undefined },
  siteId: { type: [String, Number], required: true },
  areaData: { type: Object, default: null },
  area: { type: Object, default: null },
  parentAreaId: { type: [String, Number], default: null },
  existingAreas: { type: Array, default: () => [] },
  areasList: { type: Array, default: () => [] },
})

const emit = defineEmits(['update:modelValue', 'update:isDialogVisible', 'saved'])

const isOpen = computed({
  get: () => (props.isDialogVisible !== undefined ? props.isDialogVisible : (props.modelValue ?? false)),
  set: val => {
    emit('update:modelValue', val)
    emit('update:isDialogVisible', val)
  },
})

const effectiveAreaData = computed(() => props.areaData || props.area || null)
const effectiveExistingAreas = computed(() => (props.existingAreas?.length ? props.existingAreas : (props.areasList || [])))

const store = useClientAssetStore()
const snackbarStore = useSnackbarStore()
const { t } = useI18n()
const { smAndDown } = useDisplay()

const isSubmitting = ref(false)
const errorMessage = ref('')
const nameError = ref('')
const alertRef = ref(null)
const nameRowRef = ref(null)
const flatAreas = ref([])
const hierarchyPath = ref([])
const isCodeAutoGenerated = ref(false)

const form = ref({
  parent_area_id: null,
  code: '',
  name: '',
  area_type: 'zone',
  classification: 'general',
  accessibility: 'standard',
  level_number: null,
  description: '',
  status: 'active',
  sort_order: 0,
})

const isEdit = computed(() => !!effectiveAreaData.value?.id)

const areaTypeOptions = [
  { title: 'Building / Facility', value: 'building', icon: 'tabler-building', color: 'primary' },
  { title: 'Floor / Level', value: 'floor', icon: 'tabler-stairs', color: 'info' },
  { title: 'Zone / Section', value: 'zone', icon: 'tabler-layout-dashboard', color: 'warning' },
  { title: 'Room / Office', value: 'room', icon: 'tabler-door', color: 'success' },
  { title: 'Outdoor / Yard', value: 'exterior', icon: 'tabler-trees', color: 'secondary' },
  { title: 'Roof / Terrace', value: 'roof', icon: 'tabler-sun', color: 'warning' },
  { title: 'Basement', value: 'basement', icon: 'tabler-arrow-down-bar', color: 'secondary' },
  { title: 'Other Location', value: 'other', icon: 'tabler-map-pin', color: 'primary' },
]

const classificationOptions = [
  { title: 'General / Standard', value: 'general' },
  { title: 'Production / Factory Floor', value: 'production' },
  { title: 'Storage / Warehouse', value: 'storage' },
  { title: 'Office / Administration', value: 'office' },
  { title: 'Hazardous / ATEX Zone', value: 'hazardous' },
  { title: 'Public / Reception', value: 'public' },
  { title: 'Technical / IT Room', value: 'technical' },
  { title: 'Outdoor / Perimeter', value: 'outdoor' },
]

const accessibilityOptions = [
  { title: 'Standard Access', value: 'standard' },
  { title: 'Restricted / Badge Required', value: 'restricted' },
  { title: 'High Security / Escort', value: 'high_security' },
  { title: 'Emergency Exit Only', value: 'emergency_only' },
  { title: 'Disabled / Wheelchair', value: 'wheelchair' },
  { title: 'Loading Dock / Vehicle', value: 'vehicle' },
]

const classificationItems = computed(() => classificationOptions.map(o => ({ ...o, title: t(o.title) })))
const accessibilityItems = computed(() => accessibilityOptions.map(o => ({ ...o, title: t(o.title) })))

const nameSuggestions = computed(() => {
  const type = form.value.area_type

  const map = {
    building: ['Main Building', 'Annex Block A', 'Warehouse Block', 'Admin Tower', 'Production Plant 1'],
    floor: ['Ground Floor', 'First Floor (Level 1)', 'Second Floor (Level 2)', 'Mezzanine', 'Basement Level -1'],
    zone: ['Production Zone A', 'Assembly Zone B', 'Packaging Zone', 'Logistics Loading Bay', 'Storage Bay 3'],
    room: ['Main Server Room', 'Electrical Control Room', 'Operations Control Center', 'Conference Room A', 'Executive Office'],
    exterior: ['Main Parking Lot', 'North Perimeter Yard', 'Loading Dock 1', 'Storage Yard', 'Gate 2 Entrance'],
    roof: ['HVAC Rooftop Platform', 'Solar Panel Array', 'Emergency Heli-Deck', 'Upper Terrace'],
    basement: ['Underground Technical Basement', 'Cold Storage Cellar', 'Basement Parking'],
    other: ['Staging Area', 'Temporary Workshop', 'Hazardous Waste Zone'],
  }

  return (map[type] || map.zone).map(name => t(name))
})

const loadAreas = async () => {
  if (effectiveExistingAreas.value?.length) {
    flatAreas.value = effectiveExistingAreas.value

    return
  }
  if (!props.siteId) return
  try {
    const result = await store.fetchSiteAreas(props.siteId)

    flatAreas.value = result.flat || []
  } catch (err) {
    console.error('Failed to load parent areas:', err)
  }
}

// The alert sits at the top of a scrollable body; bring it into view so errors are never missed.
const setError = async message => {
  errorMessage.value = message
  await nextTick()
  alertRef.value?.$el?.scrollIntoView({ behavior: 'smooth', block: 'nearest' })
}

const buildPathToParent = parentId => {
  if (!parentId) {
    hierarchyPath.value = []

    return
  }
  hierarchyPath.value = buildAreaBreadcrumb(parentId, flatAreas.value)
}

const selectParentArea = parentId => {
  if (isEdit.value && parentId && hasCircularDependency(effectiveAreaData.value?.id, parentId, flatAreas.value)) {
    setError(t('Cannot move an area into one of its own sub-areas.'))

    return
  }
  errorMessage.value = ''
  form.value.parent_area_id = parentId
  buildPathToParent(parentId)
}

const isParentSearchOpen = ref(false)

const onSelectParentFromDialog = area => {
  const parentId = area?.id || null

  selectParentArea(parentId)
}

const selectedParentAreaObj = computed(() => {
  if (!form.value.parent_area_id) return null

  return flatAreas.value.find(a => String(a.id) === String(form.value.parent_area_id)) || null
})

const parentFullPath = computed(() => {
  if (!selectedParentAreaObj.value) return ''

  const parts = [t('Site Root')]

  hierarchyPath.value.forEach(p => parts.push(localizedValue(p.name)))

  return parts.join(' › ')
})

const selectedTypeObj = computed(() => {
  return areaTypeOptions.find(o => o.value === form.value.area_type) || areaTypeOptions[0]
})

const fullHierarchyPreview = computed(() => {
  const parts = [t('Site Root')]

  hierarchyPath.value.forEach(p => parts.push(localizedValue(p.name)))
  if (form.value.name.trim()) {
    parts.push(form.value.name.trim())
  } else {
    parts.push(`[${t('New Area')}]`)
  }

  return parts.join(' › ')
})

watch(
  () => isOpen.value,
  async visible => {
    if (visible) {
      errorMessage.value = ''
      nameError.value = ''
      await loadAreas()

      const currentArea = effectiveAreaData.value

      if (currentArea) {
        form.value = {
          parent_area_id: currentArea.parent_area_id || null,
          code: currentArea.code || '',
          name: localizedValue(currentArea.name) || '',
          area_type: currentArea.area_type || 'zone',
          classification: currentArea.classification || 'general',
          accessibility: currentArea.accessibility || 'standard',
          level_number: currentArea.level_number || null,
          description: currentArea.description || '',
          status: currentArea.status || 'active',
          sort_order: currentArea.sort_order || 0,
        }
        buildPathToParent(currentArea.parent_area_id)
        isCodeAutoGenerated.value = false
      } else {
        const defaultType = props.parentAreaId ? 'zone' : 'building'
        const initialCode = generateShortAreaCode(defaultType, flatAreas.value)

        form.value = {
          parent_area_id: props.parentAreaId || null,
          code: initialCode,
          name: '',
          area_type: defaultType,
          classification: 'general',
          accessibility: 'standard',
          level_number: null,
          description: '',
          status: 'active',
          sort_order: 0,
        }
        isCodeAutoGenerated.value = true
        buildPathToParent(props.parentAreaId)
      }
    } else {
      hierarchyPath.value = []
    }
  },
  { immediate: true },
)

const handleClose = () => {
  emit('update:modelValue', false)
  emit('update:isDialogVisible', false)
}

const handleSubmit = async () => {
  if (!form.value.name.trim()) {
    nameError.value = t('Area name is required.')
    nameRowRef.value?.scrollIntoView({ behavior: 'smooth', block: 'center' })

    return
  }

  if (isEdit.value && form.value.parent_area_id && hasCircularDependency(effectiveAreaData.value?.id, form.value.parent_area_id, flatAreas.value)) {
    setError(t('Cannot move an area into one of its own sub-areas.'))

    return
  }

  isSubmitting.value = true
  errorMessage.value = ''
  nameError.value = ''

  try {
    const payload = {
      ...form.value,
      code: form.value.code || null,
    }

    if (isEdit.value) {
      await store.updateSiteArea(effectiveAreaData.value.id, payload)
      snackbarStore.showMessage(t('Site area updated successfully'), 'success')
    } else {
      await store.createSiteArea(props.siteId, payload)
      snackbarStore.showMessage(t('Site area created successfully'), 'success')
    }
    emit('saved')
    handleClose()
  } catch (err) {
    console.error('Error saving area:', err)
    setError(err?.data?.message || t('Failed to save site area.'))
  } finally {
    isSubmitting.value = false
  }
}

const applySuggestion = name => {
  form.value.name = name
}

const autoGenerateCode = () => {
  form.value.code = generateShortAreaCode(form.value.area_type, flatAreas.value)
  isCodeAutoGenerated.value = true
}

const onSelectAreaType = typeVal => {
  form.value.area_type = typeVal
  if (!form.value.code || isCodeAutoGenerated.value) {
    autoGenerateCode()
  }
}

watch(() => form.value.name, () => {
  if (nameError.value)
    nameError.value = ''
})
</script>

<template>
  <WpFormDialog
    :model-value="isOpen"
    :title="isEdit ? t('Edit Area / Zone') : t('Create New Area / Zone')"
    :subtitle="t('Configure hierarchical building wings, levels, production zones, and rooms')"
    :icon="selectedTypeObj.icon || 'tabler-hierarchy'"
    :icon-color="selectedTypeObj.color || 'primary'"
    size="large"
    :loading="isSubmitting"
    :submit-label="isEdit ? t('Save Area Changes') : t('Create Area')"
    @update:model-value="val => { if (!val) handleClose(); else isOpen = val; }"
    @submit="handleSubmit"
    @cancel="handleClose"
  >
    <!-- Error Alert -->
    <VAlert
          v-if="errorMessage"
          ref="alertRef"
          type="error"
          variant="tonal"
          closable
          class="mb-4"
          @click:close="errorMessage = ''"
        >
          {{ errorMessage }}
        </VAlert>

        <!-- Hierarchy Parent Breadcrumb & Selector -->
        <div class="parent-hierarchy-box pa-4 mb-5 border rounded-xl">
          <div class="d-flex align-center justify-space-between mb-2">
            <span class="text-caption font-weight-bold text-uppercase text-medium-emphasis d-flex align-center gap-1">
              <VIcon
                icon="tabler-hierarchy-2"
                size="14"
              />
              {{ t('Target Parent Location') }}
            </span>
            <VChip
              size="x-small"
              :color="form.parent_area_id ? 'primary' : 'secondary'"
              variant="tonal"
            >
              {{ form.parent_area_id ? t('Nested Sub-Area') : t('Root Facility Area') }}
            </VChip>
          </div>

          <!-- Current Hierarchy Breadcrumb Chips -->
          <div class="d-flex align-center gap-1 flex-wrap mb-3 text-body-2 font-weight-medium">
            <VChip
              size="small"
              :color="!form.parent_area_id ? 'primary' : 'default'"
              :variant="!form.parent_area_id ? 'elevated' : 'tonal'"
              class="cursor-pointer"
              @click="selectParentArea(null)"
            >
              <VIcon
                start
                icon="tabler-building-estate"
                size="14"
              />
              {{ t('Site Root') }}
            </VChip>
            <template
              v-for="crumb in hierarchyPath"
              :key="crumb.id"
            >
              <VIcon
                icon="tabler-chevron-right"
                size="14"
                class="text-disabled"
              />
              <VChip
                size="small"
                color="primary"
                variant="tonal"
                class="cursor-pointer"
                @click="selectParentArea(crumb.id)"
              >
                {{ localizedValue(crumb.name) }}
              </VChip>
            </template>
          </div>

          <!-- Selected Parent Display Card -->
          <div
            v-if="selectedParentAreaObj"
            class="selected-parent-card d-flex align-center justify-space-between flex-wrap gap-3 pa-3 rounded-lg border bg-surface"
          >
            <div class="d-flex align-center gap-3 min-w-0">
              <VAvatar
                size="40"
                color="primary"
                variant="tonal"
                rounded="lg"
              >
                <VIcon
                  :icon="resolveAreaTypeIcon(selectedParentAreaObj.area_type)"
                  size="22"
                />
              </VAvatar>
              <div class="min-w-0">
                <div class="d-flex align-center gap-2 flex-wrap">
                  <span class="text-body-2 font-weight-bold text-high-emphasis text-truncate">
                    {{ resolveAreaName(selectedParentAreaObj) }}
                  </span>
                  <VChip
                    v-if="selectedParentAreaObj.code"
                    size="x-small"
                    variant="outlined"
                    color="primary"
                    class="font-weight-medium"
                  >
                    {{ selectedParentAreaObj.code }}
                  </VChip>
                  <VChip
                    size="x-small"
                    variant="tonal"
                    color="secondary"
                    class="text-capitalize"
                  >
                    {{ selectedParentAreaObj.area_type || 'area' }}
                  </VChip>
                </div>
                <div
                  v-if="parentFullPath"
                  class="text-caption text-medium-emphasis d-flex align-center gap-1 mt-0.5 text-truncate"
                >
                  <VIcon
                    icon="tabler-git-branch"
                    size="13"
                    class="text-disabled flex-shrink-0"
                  />
                  <span class="text-truncate">{{ parentFullPath }}</span>
                </div>
              </div>
            </div>

            <div class="d-flex align-center gap-2">
              <VBtn
                variant="tonal"
                color="primary"
                size="small"
                prepend-icon="tabler-replace"
                @click="isParentSearchOpen = true"
              >
                {{ t('Change Parent') }}
              </VBtn>
              <VBtn
                variant="text"
                color="secondary"
                size="small"
                icon
                :title="t('Set to Facility Root (No Parent)')"
                @click="selectParentArea(null)"
              >
                <VIcon
                  icon="tabler-x"
                  size="18"
                />
              </VBtn>
            </div>
          </div>

          <!-- Empty Root State Card -->
          <div
            v-else
            class="empty-parent-card d-flex align-center justify-space-between flex-wrap gap-3 pa-3 rounded-lg border bg-surface"
          >
            <div class="d-flex align-center gap-3 min-w-0">
              <VAvatar
                size="40"
                color="secondary"
                variant="tonal"
                rounded="lg"
              >
                <VIcon
                  icon="tabler-building-estate"
                  size="22"
                />
              </VAvatar>
              <div class="min-w-0">
                <div class="text-body-2 font-weight-bold text-high-emphasis">
                  {{ t('Facility Root (No Parent)') }}
                </div>
                <div class="text-caption text-medium-emphasis">
                  {{ t('Top-level area directly under site root. Choose a parent if this is a nested wing, level, or room.') }}
                </div>
              </div>
            </div>

            <VBtn
              variant="tonal"
              color="primary"
              size="small"
              prepend-icon="tabler-search"
              @click="isParentSearchOpen = true"
            >
              {{ t('Browse & Select Parent') }}
            </VBtn>
          </div>
        </div>

        <VRow>
            <!-- Area Type Grid -->
            <VCol cols="12">
              <div class="d-flex align-center justify-space-between mb-2">
                <label class="text-caption font-weight-bold text-uppercase text-medium-emphasis">
                  {{ t('Area Type') }} *
                </label>
                <span class="text-caption text-disabled">{{ t('Select structure category') }}</span>
              </div>
              <div
                class="area-type-grid"
                role="group"
                :aria-label="t('Area Type')"
              >
                <div
                  v-for="opt in areaTypeOptions"
                  :key="opt.value"
                  class="area-type-card"
                  :class="{ 'is-selected': form.area_type === opt.value }"
                  role="button"
                  tabindex="0"
                  :aria-pressed="form.area_type === opt.value"
                  @click="onSelectAreaType(opt.value)"
                  @keydown.enter.prevent="onSelectAreaType(opt.value)"
                  @keydown.space.prevent="onSelectAreaType(opt.value)"
                >
                  <div class="type-icon-wrapper">
                    <VIcon
                      :icon="opt.icon"
                      size="22"
                    />
                  </div>
                  <span class="text-caption font-weight-semibold text-truncate">{{ t(opt.title) }}</span>
                  <VIcon
                    v-if="form.area_type === opt.value"
                    icon="tabler-circle-check-filled"
                    size="16"
                    class="type-check-icon"
                  />
                </div>
              </div>
            </VCol>

            <!-- Name & Auto Suggestions -->
            <VCol
              cols="12"
              md="8"
            >
              <div ref="nameRowRef">
                <AppTextField
                  v-model="form.name"
                  :label="t('Area Name') + ' *'"
                  :placeholder="t('e.g. Production Hall A, Server Room')"
                  :error-messages="nameError"
                  variant="outlined"
                  required
                />
              </div>
              <div class="d-flex flex-wrap align-center gap-1 mt-2">
                <span class="text-caption text-disabled me-1">{{ t('Suggestions') }}:</span>
                <VChip
                  v-for="suggestion in nameSuggestions.slice(0, 4)"
                  :key="suggestion"
                  size="x-small"
                  variant="tonal"
                  class="cursor-pointer suggestion-chip"
                  @click="applySuggestion(suggestion)"
                >
                  {{ suggestion }}
                </VChip>
              </div>
            </VCol>

            <!-- Area Code -->
            <VCol
              cols="12"
              md="4"
            >
              <AppTextField
                v-model="form.code"
                :label="t('Area Code / Tag')"
                :placeholder="t('e.g. ZN-01')"
                variant="outlined"
                @input="isCodeAutoGenerated = false"
              >
                <template #append-inner>
                  <IconBtn
                    size="x-small"
                    variant="text"
                    color="primary"
                    :title="t('Auto-generate simple code')"
                    :aria-label="t('Auto-generate simple code')"
                    @click="autoGenerateCode"
                  >
                    <VIcon
                      icon="tabler-sparkles"
                      size="18"
                    />
                  </IconBtn>
                </template>
              </AppTextField>
            </VCol>

            <!-- Classification -->
            <VCol
              cols="12"
              md="6"
            >
              <AppSelect
                v-model="form.classification"
                :label="t('Classification / Usage')"
                :items="classificationItems"
                variant="outlined"
                clearable
              />
            </VCol>

            <!-- Accessibility -->
            <VCol
              cols="12"
              md="6"
            >
              <AppSelect
                v-model="form.accessibility"
                :label="t('Security & Access Level')"
                :items="accessibilityItems"
                variant="outlined"
              />
            </VCol>

            <!-- Floor Number -->
            <VCol
              cols="12"
              md="4"
            >
              <AppTextField
                v-model.number="form.level_number"
                type="number"
                :label="t('Floor / Level Number')"
                :placeholder="t('e.g. 0, 1, 2, -1')"
                variant="outlined"
              />
            </VCol>

            <!-- Sort Order -->
            <VCol
              cols="12"
              md="4"
            >
              <AppTextField
                v-model.number="form.sort_order"
                type="number"
                :label="t('Sort Order')"
                variant="outlined"
              />
            </VCol>

            <!-- Status -->
            <VCol
              cols="12"
              md="4"
            >
              <AppSelect
                v-model="form.status"
                :label="t('Status')"
                :items="[
                  { title: t('Active'), value: 'active' },
                  { title: t('Inactive'), value: 'inactive' },
                  { title: t('Under Maintenance'), value: 'under_maintenance' }
                ]"
                variant="outlined"
              />
            </VCol>

            <!-- Description -->
            <VCol cols="12">
              <AppTextarea
                v-model="form.description"
                :label="t('Description & Specific Location Instructions')"
                :placeholder="t('Provide notes on access doors, hazardous materials present, or technician notes...')"
                rows="2"
                variant="outlined"
              />
            </VCol>
          </VRow>

          <!-- Live Path Summary Preview -->
          <div class="mt-4 pa-3 rounded-lg border bg-surface-variant-subtle d-flex align-center justify-space-between flex-wrap gap-2">
            <div class="d-flex align-center gap-2 min-w-0 flex-grow-1">
              <VIcon
                icon="tabler-map-pin"
                size="16"
                color="primary"
                class="flex-shrink-0"
              />
              <span class="text-caption font-weight-bold text-uppercase text-medium-emphasis flex-shrink-0">
                {{ t('Resolved Breadcrumb') }}:
              </span>
              <span
                class="text-caption font-weight-semibold text-primary text-truncate"
                :title="fullHierarchyPreview"
              >
                {{ fullHierarchyPreview }}
              </span>
            </div>
            <VChip
              size="x-small"
              :color="selectedTypeObj.color"
              variant="tonal"
            >
              {{ t(selectedTypeObj.title) }}
            </VChip>
          </div>

    <!-- Standard Tree / Cards Area Search Dialog for Target Parent Location -->
    <SiteAreaSearchDialog
      v-model="isParentSearchOpen"
      :title="t('Select Target Parent Location')"
      :site-id="props.siteId"
      :areas-list="flatAreas"
      :current-area-id="form.parent_area_id"
      :exclude-area-id="effectiveAreaData?.id"
      allow-root
      :root-label="t('Facility Root (No Parent)')"
      @select="onSelectParentFromDialog"
    />
  </WpFormDialog>
</template>

